#!/usr/bin/env node
// Turns the static preview (preview/*.html, site.css, site.js, assets) into the WordPress block theme `honamas`:
// patterns with each page's markup, page templates by slug, header and footer parts, and the theme assets.
// Run `node scripts/build-preview.mjs` first so the preview pages are current.
import { readFileSync, writeFileSync, mkdirSync, cpSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const preview = path.join(root, "preview");
const theme = path.join(root, "wp-content", "themes", "honamas");

// preview file → WordPress page slug (empty string: front page)
const pages = {
	"index.html": "",
	"die-idee.html": "die-idee",
	"2006-von-der-idee-zur-umsetzung.html": "2006-von-der-idee-zur-umsetzung",
	"die-jahre-danach.html": "die-jahre-danach",
	"wie-aus-dem-namen-eine-marke-wurde.html": "wie-aus-dem-namen-eine-marke-wurde",
	"markenschutz-eine-spaete-anerkennung.html": "markenschutz-eine-spaete-anerkennung",
	"honama.html": "der-honama",
	"die-ur-honamas.html": "die-ur-honamas",
	"erfolge.html": "erfolge",
	"film.html": "der-film",
	"impressum.html": "impressum",
};

const pageUrl = (file, hash = "") => {
	const slug = pages[file];
	if (slug === undefined) throw new Error(`No WordPress slug for ${file}`);
	return (slug ? `/${slug}/` : "/") + hash;
};

// Links become root-relative WordPress URLs; theme assets go through get_theme_file_uri().
const convert = (html, { php }) => html
	.replace(/href="([a-z0-9-]+\.html)(#[a-z0-9-]+)?"/g, (_, f, h = "") => `href="${pageUrl(f, h)}"`)
	.replace(/<a href="#">(Kontakt|Datenschutz)<\/a>/g, (_, t) => `<a href="/${t.toLowerCase()}/">${t}</a>`)
	.replace(/(src|poster|href)="assets\/([^"]+)"/g, (_, attr, p) => {
		if (!php) throw new Error(`Asset ${p} in a non-PHP file`);
		return `${attr}="<?php echo esc_url( get_theme_file_uri( 'assets/${p}' ) ); ?>"`;
	});

const between = (html, start, end) => {
	const a = html.indexOf(start);
	const b = html.indexOf(end, a);
	if (a < 0 || b < 0) throw new Error(`Markers not found: ${start} … ${end}`);
	return html.slice(a + start.length, b);
};

const read = (f) => readFileSync(path.join(preview, f), "utf8");
const write = (rel, text) => {
	const file = path.join(theme, rel);
	mkdirSync(path.dirname(file), { recursive: true });
	writeFileSync(file, text);
};

const pattern = (slug, title, html) => `<?php
/**
 * Title: ${title}
 * Slug: honamas/${slug}
 * Categories: honamas-sections
 * Inserter: no
 *
 * Generated by scripts/build-theme.mjs from preview/. Edit the preview and rebuild.
 *
 * @package Honamas
 */

?>
<!-- wp:html -->
${html.trim()}
<!-- /wp:html -->
`;

const template = (patternSlug) => `<!-- wp:template-part {"slug":"header","tagName":"header","className":"site-header"} /-->

<!-- wp:group {"tagName":"main","layout":{"type":"default"}} -->
<main class="wp-block-group">
	<!-- wp:pattern {"slug":"honamas/${patternSlug}"} /-->
</main>
<!-- /wp:group -->

<!-- wp:template-part {"slug":"footer","tagName":"div","className":"close on-dark"} /-->
`;

/* ---------- pages ---------- */
for (const [file, slug] of Object.entries(pages)) {
	if (slug === "impressum") continue; // Impressum, Datenschutz and Kontakt keep their page content (page.html).
	const html = read(file);
	let main = between(html, html.includes('<main id="top">') ? '<main id="top">' : '<main id="inhalt">', "</main>");
	if (file === "index.html") {
		// On the start page the footer sits inside the closing dark field; in WordPress it is the footer part.
		main = main.replace(/<footer class="site-footer">[\s\S]*?<\/footer>\n?/, "");
	}
	const title = between(html, "<title>", "</title>").replace(/ – HONAMAS$/, "");
	const patternSlug = `page-${slug || "home"}`;
	write(`patterns/${patternSlug}.php`, pattern(patternSlug, `HONAMAS Seite: ${title}`, convert(main, { php: true })));
	write(`templates/${slug ? `page-${slug}` : "front-page"}.html`, template(patternSlug));
}

/* ---------- header and footer parts ---------- */
const sub = read("die-idee.html");
const headerInner = between(sub, '<header class="site-header">', "</header>");
write("parts/header.html", `<!-- wp:html -->\n${convert(headerInner, { php: false }).trim()}\n<!-- /wp:html -->\n`);
const footer = `<footer class="site-footer">${between(sub, '<footer class="site-footer">', "</footer>")}</footer>`;
write("parts/footer.html", `<!-- wp:html -->\n${convert(footer, { php: false }).trim()}\n<!-- /wp:html -->\n`);

/* ---------- assets ---------- */
const css = readFileSync(path.join(preview, "site.css"), "utf8").replace(/url\("assets\/fonts\//g, 'url("../fonts/');
write("assets/css/site.css", css);
write("assets/js/site.js", readFileSync(path.join(preview, "site.js"), "utf8"));
for (const dir of ["img", "video", "docs"]) {
	const src = path.join(preview, "assets", dir);
	if (existsSync(src)) cpSync(src, path.join(theme, "assets", dir), { recursive: true }); // preview/assets/video is not in git; the theme copy is
}
if (!existsSync(path.join(theme, "assets", "fonts", "montserrat-latin-800-normal.woff2"))) throw new Error("Theme fonts missing");

console.log("theme written to", theme);
